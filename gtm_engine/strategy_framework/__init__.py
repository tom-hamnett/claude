"""Strategy Framework — data models and SQLite storage.

The Content Strategy is the layer above the Idea Bank that defines:
- Audience segments (who you're talking to)
- Content pillars (the recurring themes you own)
- Channel strategy (where you publish, what role each channel plays)
- Funnel stages (what beliefs need to form before conversion)
- Sequencing (what comes first, what comes later)

Every Idea generated downstream is tagged with a pillar_id and a
funnel_stage_id so the dashboard can show distribution, gaps, and
progress against target.
"""

import json
import logging
import sqlite3
from datetime import datetime, timezone
from pathlib import Path

from pydantic import BaseModel, ConfigDict, Field

from gtm_engine.config import SQLITE_PATH

logger = logging.getLogger(__name__)

SCHEMA_SQL = """
CREATE TABLE IF NOT EXISTS content_strategy (
    id INTEGER PRIMARY KEY DEFAULT 1,
    audience_segments TEXT,         -- JSON array
    pillars TEXT,                   -- JSON array
    channels TEXT,                  -- JSON array
    funnel_stages TEXT,             -- JSON array
    sequencing TEXT,                -- JSON array
    capacity_per_week INTEGER DEFAULT 5,
    business_phase TEXT DEFAULT 'pre_launch',
    setup_complete INTEGER DEFAULT 0,
    stages_completed TEXT,          -- JSON array of completed stage ids
    created_at TEXT,
    updated_at TEXT,
    CHECK (id = 1)
);

CREATE TABLE IF NOT EXISTS strategy_feedback (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    text TEXT NOT NULL,
    tagged_pillar TEXT,
    tagged_channel TEXT,
    tagged_funnel_stage TEXT,
    status TEXT DEFAULT 'active',   -- active | addressed | dismissed
    created_at TEXT NOT NULL,
    addressed_at TEXT
);

CREATE TABLE IF NOT EXISTS rebalance_recommendations (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    recommendation TEXT NOT NULL,
    rationale TEXT,
    severity TEXT,                  -- low | medium | high
    action_type TEXT,               -- generate | reweight | flag_gap | warn
    target_pillar TEXT,
    target_channel TEXT,
    target_funnel_stage TEXT,
    status TEXT DEFAULT 'pending',  -- pending | accepted | dismissed
    created_at TEXT NOT NULL,
    resolved_at TEXT
);
"""


