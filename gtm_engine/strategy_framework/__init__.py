# --- Pydantic models ---


class AudienceSegment(BaseModel):
    model_config = ConfigDict(extra="ignore")
    id: str
    name: str
    description: str = ""
    job_title: str = ""
    pain_points: list[str] = Field(default_factory=list)
    buying_triggers: list[str] = Field(default_factory=list)
    channels_they_use: list[str] = Field(default_factory=list)
    objections: list[str] = Field(default_factory=list)


class Pillar(BaseModel):
    model_config = ConfigDict(extra="ignore")
    id: str
    name: str
    description: str = ""
    archetype: str = ""
    target_percentage: float = 0.0
    funnel_stage: str = ""
    why_it_matters: str = ""
    example_topics: list[str] = Field(default_factory=list)


class ChannelConfig(BaseModel):
    model_config = ConfigDict(extra="ignore")
    channel_id: str
    enabled: bool = True
    cadence_per_week: int = 1
    primary_pillars: list[str] = Field(default_factory=list)
    audience_segments: list[str] = Field(default_factory=list)
    notes: str = ""


class FunnelStageConfig(BaseModel):
    model_config = ConfigDict(extra="ignore")
    id: str
    name: str
    description: str = ""
    user_definition: str = ""
    target_percentage: float = 0.0
    pillar_ids: list[str] = Field(default_factory=list)


class SequencingPhase(BaseModel):
    model_config = ConfigDict(extra="ignore")
    phase: str            # pre_launch, launch, growth, scaling
    label: str = ""
    weeks_duration: int = 4
    pillar_weights: dict[str, float] = Field(default_factory=dict)


class StrategyFeedback(BaseModel):
    model_config = ConfigDict(extra="ignore")
    id: int | None = None
    text: str
    tagged_pillar: str = ""
    tagged_channel: str = ""
    tagged_funnel_stage: str = ""
    status: str = "active"
    created_at: str = ""
    addressed_at: str = ""


class RebalanceRecommendation(BaseModel):
    model_config = ConfigDict(extra="ignore")
    id: int | None = None
    recommendation: str
    rationale: str = ""
    severity: str = "medium"          # low | medium | high
    action_type: str = "flag_gap"     # generate | reweight | flag_gap | warn
    target_pillar: str = ""
    target_channel: str = ""
    target_funnel_stage: str = ""
    status: str = "pending"
    created_at: str = ""
    resolved_at: str = ""


class ContentStrategy(BaseModel):
    model_config = ConfigDict(extra="ignore")
    audience_segments: list[AudienceSegment] = Field(default_factory=list)
    pillars: list[Pillar] = Field(default_factory=list)
    channels: list[ChannelConfig] = Field(default_factory=list)
    funnel_stages: list[FunnelStageConfig] = Field(default_factory=list)
    sequencing: list[SequencingPhase] = Field(default_factory=list)
    capacity_per_week: int = 5
    business_phase: str = "pre_launch"
    setup_complete: bool = False
    stages_completed: list[str] = Field(default_factory=list)
    created_at: str = ""
    updated_at: str = ""


class StrategyStore:
    """SQLite-backed storage for the content strategy."""

    def __init__(self, db_path: Path | None = None):
        self.db_path = db_path or SQLITE_PATH
        self.db_path.parent.mkdir(parents=True, exist_ok=True)
        self._init_schema()

    def _get_conn(self):
        """Get a DB connection — Turso if configured, local SQLite otherwise."""
        from gtm_engine.db.connection import get_connection
        return get_connection(self.db_path)

    def _connect(self) -> sqlite3.Connection:
        conn = self._get_conn()
        conn.row_factory = sqlite3.Row
        return conn

    def _init_schema(self) -> None:
        with self._connect() as conn:
            conn.executescript(SCHEMA_SQL)
            conn.commit()

    def load(self) -> ContentStrategy:
        with self._connect() as conn:
            row = conn.execute("SELECT * FROM content_strategy WHERE id = 1").fetchone()
            if not row:
                return ContentStrategy()
            return ContentStrategy(
                audience_segments=[AudienceSegment(**s) for s in json.loads(row["audience_segments"] or "[]")],
                pillars=[Pillar(**p) for p in json.loads(row["pillars"] or "[]")],
                channels=[ChannelConfig(**c) for c in json.loads(row["channels"] or "[]")],
                funnel_stages=[FunnelStageConfig(**f) for f in json.loads(row["funnel_stages"] or "[]")],
                sequencing=[SequencingPhase(**s) for s in json.loads(row["sequencing"] or "[]")],
                capacity_per_week=row["capacity_per_week"] or 5,
                business_phase=row["business_phase"] or "pre_launch",
                setup_complete=bool(row["setup_complete"]),
                stages_completed=json.loads(row["stages_completed"] or "[]"),
                created_at=row["created_at"] or "",
                updated_at=row["updated_at"] or "",
            )

    def save(self, strategy: ContentStrategy) -> None:
        now = datetime.now(timezone.utc).isoformat()
        if not strategy.created_at:
            strategy.created_at = now
        strategy.updated_at = now

        with self._connect() as conn:
            conn.execute(
                """
                INSERT OR REPLACE INTO content_strategy (
                    id, audience_segments, pillars, channels, funnel_stages,
                    sequencing, capacity_per_week, business_phase,
                    setup_complete, stages_completed, created_at, updated_at
                ) VALUES (1, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
                """,
                (
                    json.dumps([a.model_dump() for a in strategy.audience_segments]),
                    json.dumps([p.model_dump() for p in strategy.pillars]),
                    json.dumps([c.model_dump() for c in strategy.channels]),
                    json.dumps([f.model_dump() for f in strategy.funnel_stages]),
                    json.dumps([s.model_dump() for s in strategy.sequencing]),
                    strategy.capacity_per_week,
                    strategy.business_phase,
                    1 if strategy.setup_complete else 0,
                    json.dumps(strategy.stages_completed),
                    strategy.created_at,
                    strategy.updated_at,
                ),
            )
            conn.commit()

    # --- Feedback ---

    def add_feedback(self, feedback: StrategyFeedback) -> int:
        now = datetime.now(timezone.utc).isoformat()
        if not feedback.created_at:
            feedback.created_at = now
        with self._connect() as conn:
            cursor = conn.execute(
                """
                INSERT INTO strategy_feedback
                  (text, tagged_pillar, tagged_channel, tagged_funnel_stage, status, created_at)
                VALUES (?, ?, ?, ?, ?, ?)
                """,
                (
                    feedback.text, feedback.tagged_pillar, feedback.tagged_channel,
                    feedback.tagged_funnel_stage, feedback.status, feedback.created_at,
                ),
            )
            conn.commit()
            return cursor.lastrowid

    def list_feedback(self, status: str | None = None) -> list[StrategyFeedback]:
        query = "SELECT * FROM strategy_feedback"
        params: list = []
        if status:
            query += " WHERE status = ?"
            params.append(status)
        query += " ORDER BY created_at DESC"
        with self._connect() as conn:
            rows = conn.execute(query, params).fetchall()
            return [
                StrategyFeedback(
                    id=r["id"], text=r["text"],
                    tagged_pillar=r["tagged_pillar"] or "",
                    tagged_channel=r["tagged_channel"] or "",
                    tagged_funnel_stage=r["tagged_funnel_stage"] or "",
                    status=r["status"] or "active",
                    created_at=r["created_at"] or "",
                    addressed_at=r["addressed_at"] or "",
                )
                for r in rows
            ]

    def update_feedback_status(self, feedback_id: int, status: str) -> None:
        with self._connect() as conn:
            conn.execute(
                "UPDATE strategy_feedback SET status = ?, addressed_at = ? WHERE id = ?",
                (status, datetime.now(timezone.utc).isoformat(), feedback_id),
            )
            conn.commit()

    # --- Rebalance recommendations ---

    def add_recommendation(self, rec: RebalanceRecommendation) -> int:
        now = datetime.now(timezone.utc).isoformat()
        if not rec.created_at:
            rec.created_at = now
        with self._connect() as conn:
            cursor = conn.execute(
                """
                INSERT INTO rebalance_recommendations
                  (recommendation, rationale, severity, action_type,
                   target_pillar, target_channel, target_funnel_stage,
                   status, created_at)
                VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)
                """,
                (
                    rec.recommendation, rec.rationale, rec.severity, rec.action_type,
                    rec.target_pillar, rec.target_channel, rec.target_funnel_stage,
                    rec.status, rec.created_at,
                ),
            )
            conn.commit()
            return cursor.lastrowid

    def list_recommendations(self, status: str | None = "pending") -> list[RebalanceRecommendation]:
        query = "SELECT * FROM rebalance_recommendations"
        params: list = []
        if status:
            query += " WHERE status = ?"
            params.append(status)
        query += " ORDER BY severity DESC, created_at DESC"
        with self._connect() as conn:
            rows = conn.execute(query, params).fetchall()
            return [
                RebalanceRecommendation(
                    id=r["id"], recommendation=r["recommendation"],
                    rationale=r["rationale"] or "", severity=r["severity"] or "medium",
                    action_type=r["action_type"] or "flag_gap",
                    target_pillar=r["target_pillar"] or "",
                    target_channel=r["target_channel"] or "",
                    target_funnel_stage=r["target_funnel_stage"] or "",
                    status=r["status"] or "pending",
                    created_at=r["created_at"] or "",
                    resolved_at=r["resolved_at"] or "",
                )
                for r in rows
            ]

    def update_recommendation_status(self, rec_id: int, status: str) -> None:
        with self._connect() as conn:
            conn.execute(
                "UPDATE rebalance_recommendations SET status = ?, resolved_at = ? WHERE id = ?",
                (status, datetime.now(timezone.utc).isoformat(), rec_id),
            )
            conn.commit()


def get_archetype(archetype_id: str) -> dict | None:
    for a in PILLAR_ARCHETYPES:
        if a["archetype_id"] == archetype_id:
            return a
    return None


def get_funnel_stage(stage_id: str) -> dict | None:
    for s in FUNNEL_STAGES:
        if s["id"] == stage_id:
            return s
    return None


def get_channel_spec(channel_id: str) -> dict | None:
    for c in CHANNEL_CATALOGUE:
        if c["id"] == channel_id:
            return c
    return None


def get_business_phase(phase_id: str) -> dict | None:
    for p in BUSINESS_PHASES:
        if p["id"] == phase_id:
            return p
    return None
